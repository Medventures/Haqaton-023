// Generates synthetic doctor PDFs for the demo (Cyrillic via DejaVu Sans).
import { PDFDocument, rgb } from 'pdf-lib';
import fontkit from '@pdf-lib/fontkit';
import fs from 'node:fs';

const FONT = process.env.FONT || '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf';
const out = 'public/demo';
fs.mkdirSync(out, { recursive: true });

async function make(file, lines) {
  const doc = await PDFDocument.create();
  doc.registerFontkit(fontkit);
  const font = await doc.embedFont(fs.readFileSync(FONT), { subset: true });
  let page = doc.addPage([595, 842]);
  let y = 800;
  page.drawText('PRIME Green Clinic — демо-документ (синтетические данные)', { x: 40, y: 815, size: 9, font, color: rgb(0.2, 0.45, 0.3) });
  for (const line of lines) {
    if (y < 50) { page = doc.addPage([595, 842]); y = 800; }
    const bold = /^[А-ЯЁ ]{5,}(:|$)/.test(line);
    page.drawText(line, { x: 40, y, size: bold ? 12 : 11, font, color: rgb(0.07, 0.14, 0.1) });
    y -= bold ? 22 : 17;
  }
  fs.writeFileSync(`${out}/${file}`, await doc.save());
  console.log('wrote', file);
}

